/** {lang: {key: text}} built from the lists above. A list with the wrong length is skipped (falls back to English). */
export const BUILT_IN = Object.fromEntries(Object.entries(L).map(([lang, list]) => {
  if (list.length !== KEYS.length) {
    if (import.meta.env.DEV) console.warn(`i18n: "${lang}" has ${list.length} words, expected ${KEYS.length} — using English.`);
    return [lang, {}];
  }
  return [lang, Object.fromEntries(KEYS.map((k, i) => [k, list[i]]))];
}));
